all_tiers = [tier_s, tier_a, tier_b, tier_c]

with open('data/hsk3_writing.json', encoding='utf-8') as f:
    data = json.load(f)

existing_traps_dict = {t['zh']: t for t in data['kanji_traps']}

new_sorted_traps = []
rank = 1

for t_list in all_tiers:
    for item in t_list:
        char = item[0]
        tier = item[1]
        stars = item[2]
        tip = item[3]
        
        orig = existing_traps_dict.get(char, {})
        new_obj = {
            'rank': rank,
            'zh': char,
            'ja': orig.get('ja', char),
            'pinyin': orig.get('pinyin', ''),
            'hsk': orig.get('hsk', 3),
            'tier': tier,
            'stars': stars,
            'importance_label': f'Tier {tier}（重要度 ★{stars}）',
            'category': orig.get('category', 'subtle'),
            'meaning': orig.get('meaning', ''),
            'tip': tip
        }
        new_sorted_traps.append(new_obj)
        rank += 1

data['kanji_traps'] = new_sorted_traps

with open('data/hsk3_writing.json', 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

print(f'Successfully sorted {len(new_sorted_traps)} kanji traps by HSK 3 importance rank!')
